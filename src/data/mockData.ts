export function generateDailyTrends(): DailyTrendItem[] {
  const trends: DailyTrendItem[] = [];
  const startDate = new Date('2026-01-01');
  
  for (let i = 0; i < 90; i++) {
    const d = new Date(startDate);
    d.setDate(startDate.getDate() + i);
    const dateStr = d.toISOString().split('T')[0];
    
    const day = d.getDate();
    const month = d.getMonth() + 1;
    const isPeak = (month === 2 && day >= 18 && day <= 24);
    const multiplier = isPeak ? 3.8 : (1 + Math.sin(i / 4) * 0.4 + Math.random() * 0.3);
    
    const baseGmv = 85000000 * multiplier;
    const adsRatio = 0.52 + Math.random() * 0.08;
    const adsGmv = baseGmv * adsRatio;
    const organicGmv = baseGmv * (1 - adsRatio);
    
    const adsCost = adsGmv / (2.1 + Math.random() * 0.5);
    const bookingCost = 1500000 + Math.random() * 2000000;
    const commissionCost = baseGmv * 0.08;
    const totalCost = adsCost + bookingCost + commissionCost;
    
    trends.push({
      date: dateStr,
      gmvTotal: Math.round(baseGmv),
      gmvOrganic: Math.round(organicGmv),
      gmvAds: Math.round(adsGmv),
      totalCost: Math.round(totalCost),
      adsCost: Math.round(adsCost),
      bookingCost: Math.round(bookingCost),
      commissionCost: Math.round(commissionCost),
      roas: parseFloat((baseGmv / totalCost).toFixed(2)),
      views: Math.round(baseGmv * 11),
      clicks: Math.round(baseGmv * 0.45),
      orders: Math.round(baseGmv / 78000),
    });
  }
  return trends;
}

